int main(int argc, char* argv[]) {
    if (argc < 2) {
        printf("Please provide the mouse speed (1-20)\n");
        return -1;
    }

    int speed = atoi(argv[1]);

    if (speed < 1 || speed > 20) {
        printf("Speed must be between 1 and 20\n");
        return -1;
    }

    if (SystemParametersInfoW(SPI_SETMOUSESPEED, 0, (PVOID)(intptr_t)speed, SPIF_UPDATEINIFILE | SPIF_SENDCHANGE)) {
        printf("Mouse speed set to %d\n", speed);
    } else {
        printf("Failed to set mouse speed. Error code: %d\n", GetLastError());
    }

    return 0;
}
